package com.ecomove.utils;

/**
 * Énumération représentant le rôle d'un utilisateur dans le système.
 *
 * @author Darryl
 * @version 1.0
 */
public enum RoleUtilisateur {
    /** Rôle pour un utilisateur qui propose des trajets. */
    CONDUCTEUR,
    /** Rôle pour un utilisateur qui réserve des trajets. */
    PASSAGER,
    /** Rôle pour un administrateur du système. */
    ADMINISTRATEUR
}
